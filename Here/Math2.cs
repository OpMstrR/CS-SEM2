using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace pr1
{
    internal class Math2
    {

        internal static double Add2(double x, double y)
        {
            return x + y;
        }

        internal static double Subtract2(double x, double y)
        {
            return x - y;
        }

        internal static double Multiply2(double x, double y)
        {
            return x * y;
        }

        internal static double Divide2(double x, double y)
        { 
            return x / y;
        }
    }
}
